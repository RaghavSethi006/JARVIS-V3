#  STEP 2 — Python dependencies
# ─────────────────────────────────────────────
def install_python_deps():
    header("STEP 2 — Python Dependencies")

    req_path = os.path.join(ROOT, "requirements.txt")
    if not os.path.exists(req_path):
        err("requirements.txt not found at project root.")
        sys.exit(1)

    info("Installing requirements.txt ...")
    success, _, stderr = run([sys.executable, "-m", "pip", "install", "-r", req_path])
    if not success:
        err(f"pip install failed:\n{stderr}")
        sys.exit(1)
    ok("requirements.txt installed")

    # pyaudio needs special treatment on Windows
    if IS_WIN:
        info("Checking pyaudio (Windows needs special install)...")
        try:
            import pyaudio

            ok("pyaudio already installed")
        except ImportError:
            warn("pyaudio not found — trying pipwin...")
            pip_install(["pipwin"])
            success, _, _ = run([sys.executable, "-m", "pipwin", "install", "pyaudio"])
            if success:
                ok("pyaudio installed via pipwin")
            else:
                warn("pyaudio install failed. Voice input may not work.")
                warn("Manual fix: pip install pipwin && pipwin install pyaudio")

    # opencv-contrib needed for face LBPH recognizer
    info("Checking opencv-contrib-python...")
    try:
        import cv2

        if not hasattr(cv2, "face"):
            warn("opencv-python found but missing contrib. Fixing...")
            pip_install(["--force-reinstall", "opencv-contrib-python"])
            ok("opencv-contrib-python installed")
        else:
            ok("opencv-contrib-python already installed")
    except ImportError:
        pip_install(["opencv-contrib-python"])
        ok("opencv-contrib-python installed")


