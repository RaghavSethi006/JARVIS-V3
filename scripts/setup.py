def setup_biometrics():
    header("STEP 5.5 — Biometric Face Login")

    print()
    print(f"  JARVIS can recognize your face to authenticate login.")
    print(
        f"  {DIM}Uses your webcam. All data stays local — nothing is uploaded.{RESET}"
    )
    print()

    choice = ask("Set up face login now? (y/n)", "n").lower()
    if choice != "y":
        info("Skipping. Say 'register' inside JARVIS anytime to set it up later.")
        return

    # Check opencv contrib
    try:
        import cv2

        if not hasattr(cv2, "face"):
            err("opencv-contrib-python not installed.")
            err("Fix: pip install opencv-contrib-python")
            return
    except ImportError:
        err("cv2 not found. Fix: pip install opencv-contrib-python")
        return

    # Check webcam
    import cv2

    cap = cv2.VideoCapture(0)
    if not cap.isOpened():
        err("Could not open webcam. Check your camera and try again.")
        cap.release()
        return
    cap.release()
    ok("Webcam found")

    # Auto-fix opencv conflict
    info("Checking for opencv package conflict...")
    try:
        import cv2

        cv2.face.LBPHFaceRecognizer_create()
        ok("opencv-contrib-python working correctly")
    except AttributeError:
        warn("opencv conflict detected — fixing automatically...")
        run(
            [
                sys.executable,
                "-m",
                "pip",
                "uninstall",
                "opencv-python",
                "opencv-contrib-python",
                "-y",
            ]
        )
        if pip_install(["opencv-contrib-python==4.8.1.78"]):
            ok("opencv-contrib-python reinstalled cleanly")
            import importlib
            import cv2

            importlib.reload(cv2)
        else:
            err("Could not fix opencv. Run manually:")
            err("  pip uninstall opencv-python opencv-contrib-python -y")
            err("  pip install opencv-contrib-python==4.8.1.78")
            return

    print()
    print(f"  {CYAN}Instructions:{RESET}")
    print(f"  • Look directly at the camera")
    print(f"  • Keep your face centred and well-lit")
    print(f"  • The system will capture 50 samples — hold still for ~5 seconds")
    print()
    input(f"  {CYAN}?{RESET}  Press Enter when ready to start capture...")
    print()

    HAAR_XML = cv2.data.haarcascades + "haarcascade_frontalface_default.xml"
    FACE_DATA_PATH = os.path.join(ROOT, "models", "biometrics", "face_model.yml")

    detector = cv2.CascadeClassifier(HAAR_XML)
    recognizer = cv2.face.LBPHFaceRecognizer_create()

    cap = cv2.VideoCapture(0)
    faces_data = []
    labels = []
    collected = 0

    print(f"  {DIM}Capturing...{RESET}")

    for _ in range(300):
        ret, frame = cap.read()
        if not ret:
            continue
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        detected = detector.detectMultiScale(gray, 1.3, 5)
        for x, y, w, h in detected:
            face_roi = cv2.resize(gray[y : y + h, x : x + w], (200, 200))
            faces_data.append(face_roi)
            labels.append(1)
            collected += 1
        print(f"\r  Samples collected: {collected}/50", end="", flush=True)
        if collected >= 50:
            break

    cap.release()
    print()

    if collected < 10:
        err(f"Not enough face samples captured ({collected}/50).")
        err("Make sure your face is fully visible and the room is well-lit.")
        return

    recognizer.train(faces_data, np.array(labels))
    recognizer.save(FACE_DATA_PATH)
    ok(f"Face registered → face_model.yml  ({collected} samples captured)")
    ok("Say 'login' inside JARVIS to authenticate with your face.")

    env = read_env()
    env["BIOMETRICS_ENABLED"] = "true"
    write_env(env)


