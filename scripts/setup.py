def verify():
    header("STEP 7 — Final Verification")

    file_checks = {
        "frontend/dist/index.html": "Frontend build",
        "config/.env": ".env config",
        "contacts.csv": "contacts.csv",
        "requirements.txt": "requirements.txt",
    }

    all_good = True
    for rel_path, label in file_checks.items():
        full = os.path.join(ROOT, rel_path)
        if os.path.exists(full):
            ok(label)
        else:
            warn(f"{label} missing  ({rel_path})")
            all_good = False

    import_checks = [
        ("webview", "pywebview"),
        ("speech_recognition", "SpeechRecognition"),
        ("pyttsx3", "pyttsx3"),
        ("cv2", "opencv-contrib-python"),
        ("selenium", "selenium"),
        ("pywhatkit", "pywhatkit"),
    ]

    print()
    for module, pkg_name in import_checks:
        try:
            __import__(module)
            ok(pkg_name)
        except ImportError:
            warn(f"{pkg_name} not importable — pip install {pkg_name}")
            all_good = False

    try:
        import pyaudio

        ok("pyaudio (voice input)")
    except ImportError:
        warn("pyaudio missing — voice input disabled")
        if IS_WIN:
            warn("  Fix: pip install pipwin && pipwin install pyaudio")

    model = os.path.join(ROOT, "models", "Llama-3.2-3B-Instruct-Q4KM.gguf")
    face = os.path.join(ROOT, "models", "biometrics", "face_model.yml")

    if os.path.exists(model):
        ok("LLM model file")
    else:
        env = read_env()
        if env.get("LLM_MODE") == "api":
            ok("LLM mode → API (no model file needed)")
        else:
            warn("LLM model not found — run: python scripts/downloadmodel.py")

    if os.path.exists(face):
        ok("Face data (face_model.yml)")
    else:
        info("No face data — say 'register' in JARVIS to set up face login")

    return all_good


