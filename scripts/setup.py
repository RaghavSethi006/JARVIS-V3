def configure_env():
    header("STEP 4 — Configuration (.env)")

    existing = read_env()

    if existing:
        warn(".env already exists — will update only fields you fill in.")

    print()
    print(f"  {DIM}Press Enter to skip any field you don't need yet.{RESET}")
    print()

    def prompt_field(key, label, default="", secret=False):
        current = existing.get(key, default)
        display = f"{'*' * len(current)}" if (secret and current) else current
        prompt_str = f"{label}{f' (current: {display})' if current else ''}"
        val = ask(prompt_str, current)
        existing[key] = val

    prompt_field(
        "OPENWEATHER_API_KEY", "OpenWeather API key  →  https://openweathermap.org/api"
    )
    prompt_field("DEFAULT_CITY", "Default city for weather", "Calgary")
    prompt_field("EMAIL_ADDRESS", "Gmail address for email skill")
    prompt_field(
        "EMAIL_PASSWORD",
        "Gmail App Password  →  myaccount.google.com/apppasswords",
        secret=True,
    )
    prompt_field("NEWSAPI_KEY", "NewsAPI key  →  https://newsapi.org")

    write_env(existing)
    ok("config/.env saved")


