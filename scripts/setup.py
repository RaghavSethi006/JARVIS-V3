# ─────────────────────────────────────────────
#  Colours (no dependencies needed)
# ─────────────────────────────────────────────
RESET = "\033[0m"
BOLD = "\033[1m"
CYAN = "\033[96m"
GREEN = "\033[92m"
YELLOW = "\033[93m"
RED = "\033[91m"
DIM = "\033[2m"


def c(color, text):
    return f"{color}{text}{RESET}"


def header(text):
    print(
        f"\n{BOLD}{CYAN}{'─'*52}{RESET}\n{BOLD}{CYAN}  {text}{RESET}\n{BOLD}{CYAN}{'─'*52}{RESET}"
    )


def ok(text):
    print(f"  {GREEN}✓{RESET}  {text}")


def warn(text):
    print(f"  {YELLOW}⚠{RESET}  {text}")


def err(text):
    print(f"  {RED}✗{RESET}  {text}")


def info(text):
    print(f"  {DIM}→{RESET}  {text}")


def ask(prompt, default=""):
    val = input(
        f"  {CYAN}?{RESET}  {prompt}{f' [{default}]' if default else ''}: "
    ).strip()
    return val if val else default


