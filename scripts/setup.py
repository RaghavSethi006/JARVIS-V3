def check_python():
    header("STEP 1 — Python Version")
    major, minor = sys.version_info[:2]
    if major < 3 or minor < 10:
        err(f"Python 3.10+ required. You have {major}.{minor}.")
        err("Download from https://python.org")
        sys.exit(1)
    ok(f"Python {major}.{minor} detected")


