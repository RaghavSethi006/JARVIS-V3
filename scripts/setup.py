# ─────────────────────────────────────────────
def build_frontend():
    header("STEP 3 — Frontend (React / Vite)")

    node_ok, node_ver, _ = run(["node", "--version"], capture=True)
    if not node_ok:
        err("Node.js not found.")
        err("Download from https://nodejs.org (LTS version)")
        sys.exit(1)
    ok(f"Node.js {node_ver.strip()} detected")

    npm_ok, npm_ver, _ = run(["npm", "--version"], capture=True)
    if not npm_ok:
        err("npm not found. Reinstall Node.js.")
        sys.exit(1)
    ok(f"npm {npm_ver.strip()} detected")

    frontend_dir = os.path.join(ROOT, "frontend")
    if not os.path.exists(frontend_dir):
        err("frontend/ directory not found.")
        sys.exit(1)

    info("Running npm install (this may take a minute)...")
    success, _, stderr = run(["npm", "install"], cwd=frontend_dir)
    if not success:
        err(f"npm install failed:\n{stderr}")
        sys.exit(1)
    ok("npm packages installed")

    info("Building frontend with Vite...")
    success, _, stderr = run(["npm", "run", "build"], cwd=frontend_dir)
    if not success:
        err(f"Vite build failed:\n{stderr}")
        sys.exit(1)

    dist_index = os.path.join(frontend_dir, "dist", "index.html")
    if not os.path.exists(dist_index):
        err("Build finished but dist/index.html not found.")
        sys.exit(1)
    ok("Frontend built → frontend/dist/")


