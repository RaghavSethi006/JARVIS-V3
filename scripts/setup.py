def setup_contacts():
    header("STEP 5 — WhatsApp Contacts (contacts.csv)")

    csv_path = os.path.join(ROOT, "contacts.csv")

    if os.path.exists(csv_path):
        ok("contacts.csv already exists — skipping")
        return

    print()
    print(f"  {DIM}Add contacts for the WhatsApp skill.{RESET}")
    print(f"  {DIM}Phone must be in international format: +14031234567{RESET}")
    print(f"  {DIM}Press Enter with no name to finish.{RESET}")
    print()

    rows = []
    while True:
        name = ask("Contact name (or Enter to finish)").strip()
        if not name:
            break
        phone = ask(f"Phone for {name}  (e.g. +14031234567)").strip()
        if phone:
            rows.append((name, phone))

    with open(csv_path, "w") as f:
        f.write("Name,Phone\n")
        for name, phone in rows:
            f.write(f"{name},{phone}\n")

    if rows:
        ok(f"contacts.csv created with {len(rows)} contact(s)")
    else:
        ok("contacts.csv created (empty — add contacts anytime)")


