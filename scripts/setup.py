# scripts/setup.py → ROOT is one level up
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IS_WIN = platform.system() == "Windows"


def run(cmd, cwd=None, capture=False):
    try:
        result = subprocess.run(
            cmd, cwd=cwd or ROOT, shell=IS_WIN, capture_output=capture, text=True
        )
        return result.returncode == 0, result.stdout, result.stderr
    except FileNotFoundError:
        return False, "", "command not found"


def pip_install(packages: list):
    ok_flag, _, _ = run(
        [sys.executable, "-m", "pip", "install", "--upgrade", *packages]
    )
    return ok_flag


def read_env():
    env_path = os.path.join(ROOT, "config", ".env")
    existing = {}
    if os.path.exists(env_path):
        with open(env_path, "r") as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#") and "=" in line:
                    k, _, v = line.partition("=")
                    existing[k.strip()] = v.strip()
    return existing


def write_env(data: dict):
    env_path = os.path.join(ROOT, "config", ".env")
    os.makedirs(os.path.dirname(env_path), exist_ok=True)
    with open(env_path, "w") as f:
        f.write("# JARVIS Configuration — generated by setup.py\n\n")
        for k, v in data.items():
            f.write(f"{k}={v}\n")


